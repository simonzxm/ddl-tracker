import { spawnSync } from 'node:child_process';
import { createHash } from 'node:crypto';
import {
  copyFileSync,
  existsSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import { resolve } from 'node:path';
import process from 'node:process';

const root = resolve(import.meta.dirname, '..');
const api = resolve(root, 'apps/api');
const actualVars = resolve(api, '.dev.vars');
const exampleVars = resolve(api, '.dev.vars.example');
const createdVars = !existsSync(actualVars);
const migrationDirectory = resolve(api, 'drizzle');
const latestMigrationModule = resolve(api, 'src/db/latest-migration.ts');

function run(command, args, cwd = root) {
  const result = spawnSync(command, args, {
    cwd,
    encoding: 'utf8',
    stdio: 'inherit',
  });
  if (result.error !== undefined) throw result.error;
  if (result.status !== 0) process.exit(result.status ?? 1);
}

try {
  if (createdVars) copyFileSync(exampleVars, actualVars);
  run('pnpm', ['exec', 'wrangler', 'types', '--env-interface', 'Env', '--strict-vars', 'false'], api);
} finally {
  if (createdVars) rmSync(actualVars, { force: true });
}

run('git', ['diff', '--exit-code', '--', 'apps/api/worker-configuration.d.ts']);
run('pnpm', ['--filter', '@ddl-tracker/api', 'db:generate']);
run('git', ['diff', '--exit-code', '--', 'apps/api/drizzle']);

const migrations = readdirSync(migrationDirectory)
  .filter((name) => /^\d{4}_.+\.sql$/u.test(name))
  .sort();
const latestMigration = migrations.at(-1);
if (latestMigration === undefined) {
  throw new Error('No Drizzle SQL migrations were found.');
}
const migrationHash = createHash('sha256')
  .update(readFileSync(resolve(migrationDirectory, latestMigration)))
  .digest('hex');
writeFileSync(
  latestMigrationModule,
  `// Generated by scripts/verify-generated.mjs. Do not edit manually.\nexport const latestMigrationHash =\n  '${migrationHash}';\n`,
);
run('git', ['diff', '--exit-code', '--', 'apps/api/src/db/latest-migration.ts']);
